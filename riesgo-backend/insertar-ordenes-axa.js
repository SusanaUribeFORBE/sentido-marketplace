async function insertar() {
  console.log(`Insertando ${ordenes.length} órdenes en Supabase con datos completos...`);

  const { data, error } = await supabase
    .from('axa_ordenes')
    .upsert(ordenes, { onConflict: 'numero_orden', ignoreDuplicates: false })
    .select();

  if (error) {
    console.error('❌ Error:', error.message);
    process.exit(1);
  }

  console.log(`✅ ${data.length} órdenes insertadas/actualizadas correctamente.\n`);
  data.forEach(o => console.log(
    `  • ${o.numero_orden.padEnd(20)} ${o.nombre_trabajador.padEnd(38)} ${o.codigo_actividad?.padEnd(7)} $${Number(o.valor_servicio).toLocaleString('es-CO')}`
  ));
}

